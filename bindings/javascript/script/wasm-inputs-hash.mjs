#!/usr/bin/env node
/**
 * Hash the inputs that affect bindings/javascript/wasm artifacts.
 *
 * Usage:
 *   node script/wasm-inputs-hash.mjs              # print hash (working tree)
 *   node script/wasm-inputs-hash.mjs --write      # write wasm/.inputs-sha256
 *   node script/wasm-inputs-hash.mjs --check      # exit 1 if stamp mismatches
 *   node script/wasm-inputs-hash.mjs --ref HEAD --write
 *       # hash file contents from a git ref (useful when the working tree is dirty)
 */
import { spawnSync } from 'node:child_process'
import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const pkgRoot = path.resolve(__dirname, '..')
const repoRoot = path.resolve(pkgRoot, '../..')
const stampPath = path.join(pkgRoot, 'wasm', '.inputs-sha256')

/** Dirs/files under repo root that affect the committed wasm. */
const INPUT_SPECS = [
  'bindings/javascript/embind',
  'bindings/javascript/script/build-wasm.mjs',
  'src',
  'include'
]

/** package.json script keys whose flags affect the wasm binary. */
const PACKAGE_SCRIPT_KEYS = ['build:prepare', 'build:obj', 'build:wasm']

function fail(msg) {
  console.error(msg)
  process.exit(1)
}

function git(args, options = {}) {
  const r = spawnSync('git', args, {
    cwd: repoRoot,
    encoding: 'buffer',
    maxBuffer: 64 * 1024 * 1024,
    ...options
  })
  if (r.status !== 0) {
    const err = (r.stderr && r.stderr.toString('utf8')) || `git ${args.join(' ')} failed`
    fail(err.trim())
  }
  return r.stdout
}

function shouldIncludeFile(relPosix) {
  const base = path.posix.basename(relPosix)
  if (base.endsWith('.bak') || base.endsWith('~')) return false
  if (base === '.DS_Store' || base === 'Thumbs.db') return false
  return true
}

function collectInputPaths(ref) {
  // Prefer git inventory so generated Makefile.in etc. are ignored.
  // Worktree mode also includes untracked (non-ignored) files so a new
  // embind *.cpp is hashed before the first git add.
  const out = ref
    ? git(['ls-tree', '-r', '--name-only', '-z', ref, '--', ...INPUT_SPECS])
    : git([
        'ls-files',
        '-z',
        '-c',
        '-o',
        '--exclude-standard',
        '--',
        ...INPUT_SPECS
      ])
  const files = out
    .toString('utf8')
    .split('\0')
    .filter(Boolean)
    .map((p) => p.replace(/\\/g, '/'))
    .filter(shouldIncludeFile)
  files.sort()
  if (!files.length) {
    fail(
      ref
        ? `No wasm input files found in git ref ${ref}`
        : 'No tracked wasm input files found'
    )
  }
  return files
}

function sha256(buf) {
  return crypto.createHash('sha256').update(buf).digest('hex')
}

function readWorktreeFile(rel) {
  return fs.readFileSync(path.join(repoRoot, rel))
}

function readGitFile(ref, rel) {
  return git(['show', `${ref}:${rel}`])
}

function readPackageScripts(ref) {
  const raw = ref
    ? readGitFile(ref, 'bindings/javascript/package.json')
    : readWorktreeFile('bindings/javascript/package.json')
  const pkg = JSON.parse(raw.toString('utf8'))
  return pkg.scripts || {}
}

function computeHash(ref) {
  const files = collectInputPaths(ref)
  const digest = crypto.createHash('sha256')

  for (const rel of files) {
    const content = ref ? readGitFile(ref, rel) : readWorktreeFile(rel)
    digest.update(rel)
    digest.update('\0')
    digest.update(sha256(content))
    digest.update('\n')
  }

  // Configure / make flags live in package.json scripts; version bumps alone
  // must not force a rebuild, so only hash the relevant script bodies.
  const scripts = readPackageScripts(ref)
  for (const key of PACKAGE_SCRIPT_KEYS) {
    const body = scripts[key] ?? ''
    digest.update(`package.json:scripts.${key}`)
    digest.update('\0')
    digest.update(body)
    digest.update('\n')
  }

  return {
    hash: digest.digest('hex'),
    fileCount: files.length
  }
}

function readStamp() {
  if (!fs.existsSync(stampPath)) return null
  const text = fs.readFileSync(stampPath, 'utf8').trim()
  const line = text.split(/\r?\n/)[0] || ''
  const hash = line.split(/\s+/)[0]
  return hash || null
}

function writeStamp(hash) {
  const dir = path.dirname(stampPath)
  fs.mkdirSync(dir, { recursive: true })
  const payload =
    `${hash}  wasm-inputs\n` +
    `# Generated by script/wasm-inputs-hash.mjs — do not edit by hand.\n` +
    `# Covers: embind/, src/, include/, build-wasm.mjs, selected package.json scripts.\n`
  fs.writeFileSync(stampPath, payload, 'utf8')
}

function parseRef(argv) {
  const idx = argv.indexOf('--ref')
  if (idx === -1) return null
  const ref = argv[idx + 1]
  if (!ref || ref.startsWith('-')) {
    fail('Usage: --ref <git-ref>')
  }
  return ref
}

const argv = process.argv.slice(2)
const ref = parseRef(argv)
const args = new Set(
  argv.filter((a, i) => a !== '--ref' && !(i > 0 && argv[i - 1] === '--ref'))
)
const { hash, fileCount } = computeHash(ref)

if (args.has('--write')) {
  writeStamp(hash)
  console.log(
    `Wrote ${path.relative(repoRoot, stampPath)} (${fileCount} files` +
      `${ref ? `, ref ${ref}` : ''})`
  )
  console.log(hash)
  process.exit(0)
}

if (args.has('--check')) {
  const stamped = readStamp()
  if (!stamped) {
    fail(
      `Missing ${path.relative(repoRoot, stampPath)}.\n` +
        `Rebuild wasm locally, then run: pnpm copy`
    )
  }
  if (stamped !== hash) {
    fail(
      `WASM inputs changed but ${path.relative(repoRoot, stampPath)} is stale.\n` +
        `  stamped: ${stamped}\n` +
        `  current: ${hash}\n` +
        `Rebuild with:\n` +
        `  pnpm build:prepare && pnpm build:obj && pnpm build:wasm && pnpm copy\n` +
        `Then commit bindings/javascript/wasm/ (including .inputs-sha256).`
    )
  }
  console.log(`WASM inputs stamp OK (${fileCount} files)`)
  process.exit(0)
}

console.log(hash)
console.log(`# ${fileCount} input files${ref ? ` (ref ${ref})` : ''}`)
